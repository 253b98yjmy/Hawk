"""Generates src/net/hk_psl_data.inc from the Public Suffix List.

Usage: python tools/gen_psl.py [public_suffix_list.dat]
Without an argument the list is downloaded from publicsuffix.org.

Rules are stored as an open-addressing hash table of 64-bit FNV-1a hashes of the rule text
('!' marks exception rules, '*.' wildcard rules, as in the list itself). Lookups hash a
candidate and probe; with ~10^4 rules a false match of a 64-bit hash is not a practical concern.
"""
import pathlib
import sys
import urllib.request

URL = "https://publicsuffix.org/list/public_suffix_list.dat"
OUT = pathlib.Path(__file__).resolve().parent.parent / "src" / "net" / "hk_psl_data.inc"

FNV_OFFSET = 0xCBF29CE484222325
FNV_PRIME = 0x100000001B3
MASK = (1 << 64) - 1


def fnv1a(s: str) -> int:
    h = FNV_OFFSET
    for b in s.encode("ascii"):
        h = ((h ^ b) * FNV_PRIME) & MASK
    return h or 1


def parse(text: str) -> set:
    rules = set()
    for line in text.splitlines():
        line = line.strip()
        if not line or line.startswith("//"):
            continue
        rule = line.split()[0].lower()
        # Store the ASCII (Punycode) form: hosts reach the PSL after IDNA processing.
        labels = []
        for label in rule.split("."):
            if label in ("*",) or label.startswith("!") or label.isascii():
                labels.append(label)
            else:
                labels.append("xn--" + label.encode("punycode").decode("ascii"))
        rules.add(".".join(labels))
    return rules


def emit(rules: set) -> None:
    cap = 1
    while cap < len(rules) * 3 // 2:
        cap *= 2
    table = [0] * cap
    for r in sorted(rules):
        h = fnv1a(r)
        i = h & (cap - 1)
        while table[i]:
            if table[i] == h:
                raise SystemExit(f"hash collision on {r!r}")
            i = (i + 1) & (cap - 1)
        table[i] = h
    lines = [
        "/* Generated by tools/gen_psl.py from the Public Suffix List (MPL-2.0). Do not edit. */",
        f"#define HK_PSL_RULES {len(rules)}",
        f"#define HK_PSL_CAP {cap}",
        "static const uint64_t k_psl_table[HK_PSL_CAP] = {",
    ]
    for i in range(0, cap, 4):
        lines.append("    " + " ".join(f"0x{v:016x}ull," for v in table[i : i + 4]))
    lines.append("};")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {len(rules)} rules ({cap} slots) to {OUT}")


def main() -> None:
    if len(sys.argv) > 1:
        text = pathlib.Path(sys.argv[1]).read_text(encoding="utf-8")
    else:
        with urllib.request.urlopen(URL) as r:
            text = r.read().decode("utf-8")
    emit(parse(text))


if __name__ == "__main__":
    main()
