"""Generates src/net/hk_psl_data.inc from the Public Suffix List.

Usage: python tools/gen_psl.py [public_suffix_list.dat]
Without an argument the list is downloaded from publicsuffix.org.
Rules are stored as a sorted array of strings (binary searched at run time):
'!' marks exception rules, '*.' wildcard rules (as in the list itself).
"""
import pathlib
import sys
import urllib.request

URL = "https://publicsuffix.org/list/public_suffix_list.dat"
OUT = pathlib.Path(__file__).resolve().parent.parent / "src" / "net" / "hk_psl_data.inc"


def main() -> None:
    if len(sys.argv) > 1:
        text = pathlib.Path(sys.argv[1]).read_text(encoding="utf-8")
    else:
        with urllib.request.urlopen(URL) as r:
            text = r.read().decode("utf-8")
    rules = set()
    for line in text.splitlines():
        line = line.strip()
        if not line or line.startswith("//"):
            continue
        rule = line.split()[0].lower()
        # Store the ASCII (Punycode) form: hosts reach the PSL after IDNA processing.
        labels = []
        for label in rule.split("."):
            if label in ("*",) or label.startswith("!") or label.isascii():
                labels.append(label)
            else:
                labels.append("xn--" + label.encode("punycode").decode("ascii"))
        rules.add(".".join(labels))
    ordered = sorted(rules)
    # One literal per rule: MSVC limits a concatenated string literal to 64 KiB.
    lines = [
        "/* Generated by tools/gen_psl.py from the Public Suffix List (MPL-2.0). Do not edit. */",
        f"#define HK_PSL_RULES {len(ordered)}",
        "static const char *const k_psl_rules[HK_PSL_RULES] = {",
    ]
    for r in ordered:
        lines.append('    "' + r.replace("\\", "\\\\").replace('"', '\\"') + '",')
    lines.append("};")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {len(ordered)} rules to {OUT}")


if __name__ == "__main__":
    main()
