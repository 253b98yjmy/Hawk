"""Generates src/html/hk_html_entities.inc from the WHATWG entities.json.

Usage: python tools/gen_entities.py [path/to/entities.json]
Without an argument the file is downloaded from html.spec.whatwg.org.
"""
import json
import pathlib
import sys
import urllib.request

URL = "https://html.spec.whatwg.org/entities.json"
OUT = pathlib.Path(__file__).resolve().parent.parent / "src" / "html" / "hk_html_entities.inc"


def main() -> None:
    if len(sys.argv) > 1:
        data = json.loads(pathlib.Path(sys.argv[1]).read_text(encoding="utf-8"))
    else:
        with urllib.request.urlopen(URL) as r:
            data = json.loads(r.read().decode("utf-8"))

    entries = []
    for name, info in data.items():
        assert name.startswith("&")
        cps = info["codepoints"]
        assert 1 <= len(cps) <= 2 and (len(cps) == 1 or cps[1] <= 0xFFFF)
        entries.append((name[1:].encode("ascii"), cps[0], cps[1] if len(cps) == 2 else 0))
    entries.sort(key=lambda e: e[0])  # byte order, matches memcmp

    pool = bytearray()
    rows = []
    for name, cp1, cp2 in entries:
        rows.append(f"    {{{len(pool)}, {len(name)}, 0x{cp1:X}, 0x{cp2:X}}},")
        pool += name
    assert len(pool) < 65536

    lines = [
        "/* Generated by tools/gen_entities.py from the WHATWG entities.json. Do not edit. */",
        f"#define HK_ENTITY_COUNT {len(entries)}",
        f"#define HK_ENTITY_MAX_NAME {max(len(e[0]) for e in entries)}",
        "static const char k_entity_pool[] =",
    ]
    for i in range(0, len(pool), 72):
        chunk = pool[i : i + 72].decode("ascii")
        lines.append(f'    "{chunk}"')
    lines[-1] += ";"
    lines.append("static const hk_entity k_entities[HK_ENTITY_COUNT] = {")
    lines += rows
    lines.append("};")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {len(entries)} entities to {OUT}")


if __name__ == "__main__":
    main()
